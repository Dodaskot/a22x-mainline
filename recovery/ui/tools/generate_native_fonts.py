#!/usr/bin/env python3
"""Build-time glyph atlases at native panel size. The UI needs no font engine.

Each glyph is drawn at eight times its size and reduced with a box filter, which
gives exact, unhinted coverage. Advances stay in 1/64 pixel, so words keep their
real spacing. Layout runs on a 720x1600 grid; one unit is 1.5 panel pixels.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
SANS = Path('/usr/share/fonts/Adwaita/AdwaitaSans-Regular.ttf')
FALLBACK = {400: 'Regular', 500: 'Medium', 600: 'Bold', 700: 'Bold'}
MONO = Path('/usr/share/fonts/TTF/JetBrainsMonoNLNerdFontMono-Regular.ttf')
MONO_FALLBACK = Path('/usr/share/fonts/Adwaita/AdwaitaMono-Regular.ttf')
# Panel pixels, weight, and baseline from the top of the text line.
STYLES = [(30, 400, 29), (39, 500, 38), (51, 600, 48), (75, 700, 71)]
MONO_SIZE, MONO_BASELINE = 32, 29
SCALE = 8
# Coverage is blended in sRGB, which thins light text on a dark surface.
GAMMA = 0.8
LUT = bytes(round(255 * (value / 255) ** GAMMA) for value in range(256))
EXTRA = sorted(set(range(0xA0, 0x180)) | set(range(0x400, 0x500)) |
               {0x2010, 0x2011, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D,
                0x2022, 0x2026, 0x20AC, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0xFFFD})
TERMINAL = sorted(set(range(32, 127)) | set(range(0xA0, 0x180)) | set(range(0x300, 0x370)) |
                  set(range(0x400, 0x500)) | set(range(0x2500, 0x2580)) |
                  {0x2190, 0x2191, 0x2192, 0x2193, 0x2022, 0x2026, 0x20AC, 0x2264, 0x2265,
                   0x2260, 0x3C0, 0x25C6, 0x2592, 0x2409, 0x240C, 0x240D, 0x240A, 0x2424,
                   0x240B, 0x23BA, 0x23BB, 0x23BC, 0x23BD, 0xFFFD})


def sans(size, weight):
    font = ImageFont.truetype(str(SANS), size * SCALE)
    font.set_variation_by_axes([min(32, max(14, size / 2.5)), weight])
    return font


def covered(path):
    from fontTools.ttLib import TTFont
    return set(TTFont(str(path), lazy=True).getBestCmap())


def raster(font, point, baseline):
    """Return alpha bytes and (width, height, x, y, advance in 1/64 pixel)."""
    ch = chr(point)
    x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
    advance = round(font.getlength(ch) / SCALE * 64)
    if x1 <= x0 or y1 <= y0:
        return b'', (0, 0, 0, baseline, advance)
    left, top = x0 // SCALE, y0 // SCALE
    width, height = -(-x1 // SCALE) - left, -(-y1 // SCALE) - top
    image = Image.new('L', (width * SCALE, height * SCALE))
    ImageDraw.Draw(image).text((-left * SCALE, -top * SCALE), ch, font=font, fill=255, anchor='ls')
    small = image.reduce(SCALE).point(LUT)
    return small.tobytes(), (width, height, left, baseline + top, advance)


def table(points, styles):
    atlas, tables = bytearray(), []
    for font_for, baseline in styles:
        rows = []
        for point in points:
            data, (w, h, x, y, advance) = raster(font_for(point), point, baseline)
            rows.append((len(atlas), w, h, x, y, advance))
            atlas.extend(data)
        tables.append(rows)
    return tables, atlas


def emit_rows(out, rows):
    for row in rows:
        out.write('{' + ','.join(map(str, row)) + '},\n')


def emit_bytes(out, atlas):
    for n in range(0, len(atlas), 32):
        out.write(','.join(map(str, atlas[n:n + 32])) + ',\n')


have = covered(SANS)
missing = [point for point in list(range(32, 127)) + EXTRA if point not in have]
styles = []
for size, weight, baseline in STYLES:
    main = sans(size, weight)
    other = ImageFont.truetype(f'/usr/share/fonts/noto/NotoSans-{FALLBACK[weight]}.ttf', size * SCALE)
    styles.append(((lambda point, main=main, other=other: main if point in have else other), baseline))

ascii_points = list(range(32, 127))
tables, atlas = table(ascii_points, styles)
with (ROOT / 'font_data.h').open('w') as out:
    out.write('/* Generated by tools/generate_native_fonts.py; see LICENSE.fonts. */\n')
    out.write('#ifndef A22X_FONT_DATA_H\n#define A22X_FONT_DATA_H\n#include <stdint.h>\n')
    out.write('/* Sizes and offsets are panel pixels; advance is in 1/64 pixel. */\n')
    out.write('typedef struct { uint32_t off; int16_t w,h,x,y,advance; } Glyph;\n')
    out.write('static const Glyph glyphs[4][95] = {\n')
    for rows in tables:
        out.write('{\n')
        emit_rows(out, rows)
        out.write('},\n')
    out.write('};\nstatic const uint8_t font_alpha[] = {\n')
    emit_bytes(out, atlas)
    out.write('};\n#endif\n')
extra_tables, extra_atlas = table(EXTRA, styles)
with (ROOT / 'font_extra.h').open('w') as out:
    out.write('/* Generated by tools/generate_native_fonts.py; see LICENSE.fonts. */\n')
    out.write('#ifndef A22X_FONT_EXTRA_H\n#define A22X_FONT_EXTRA_H\n')
    out.write(f'#define EXTRA_GLYPHS {len(EXTRA)}\n')
    out.write('static const uint32_t extra_codepoints[EXTRA_GLYPHS] = {\n')
    out.write(','.join(hex(point) for point in EXTRA) + '\n};\n')
    out.write('static const Glyph extra_glyphs[4][EXTRA_GLYPHS] = {\n')
    for rows in extra_tables:
        out.write('{\n')
        emit_rows(out, rows)
        out.write('},\n')
    out.write('};\nstatic const uint8_t extra_font_alpha[] = {\n')
    emit_bytes(out, extra_atlas)
    out.write('};\n#endif\n')
mono = ImageFont.truetype(str(MONO), MONO_SIZE * SCALE)
mono_other = ImageFont.truetype(str(MONO_FALLBACK), MONO_SIZE * SCALE)
mono_have = covered(MONO)
mono_tables, mono_atlas = table(TERMINAL, [((lambda point: mono if point in mono_have else mono_other), MONO_BASELINE)])
with (ROOT / 'terminal_font.h').open('w') as out:
    out.write('/* Generated by tools/generate_native_fonts.py; see LICENSE.fonts. */\n')
    out.write('#ifndef A22X_TERMINAL_FONT_H\n#define A22X_TERMINAL_FONT_H\n')
    out.write(f'#define TERMINAL_GLYPHS {len(TERMINAL)}\nstatic const uint32_t terminal_codepoints[TERMINAL_GLYPHS]={{\n')
    out.write(','.join(hex(point) for point in TERMINAL) + '\n};\n')
    out.write('static const Glyph terminal_glyphs[TERMINAL_GLYPHS]={\n')
    emit_rows(out, mono_tables[0])
    out.write('};\nstatic const uint8_t terminal_font_alpha[]={\n')
    emit_bytes(out, mono_atlas)
    out.write('};\n#endif\n')
# The lock screen clock needs digits far larger than any text, so it gets its own small atlas.
CLOCK = [ord(c) for c in '0123456789:']
CLOCK_SIZE, CLOCK_WEIGHT = 252, 300
clock = sans(CLOCK_SIZE, CLOCK_WEIGHT)
clock_tables, clock_atlas = table(CLOCK, [((lambda point: clock), round(CLOCK_SIZE * .95))])
# The password pad wants thin digits like the clock's.
PAD_DIGITS = [ord(c) for c in '0123456789']
PAD_DIGIT_SIZE, PAD_DIGIT_WEIGHT = 126, 300
pad_digit = sans(PAD_DIGIT_SIZE, PAD_DIGIT_WEIGHT)
pad_tables, pad_atlas = table(PAD_DIGITS, [((lambda point: pad_digit), round(PAD_DIGIT_SIZE * .95))])
with (ROOT / 'clock_font.h').open('w') as out:
    out.write('/* Generated by tools/generate_native_fonts.py; see LICENSE.fonts. */\n')
    out.write('#ifndef A22X_CLOCK_FONT_H\n#define A22X_CLOCK_FONT_H\n')
    out.write(f'#define CLOCK_GLYPH_HEIGHT {CLOCK_SIZE}\nstatic const Glyph clock_glyphs[11]={{\n')
    emit_rows(out, clock_tables[0])
    out.write('};\nstatic const uint8_t clock_font_alpha[]={\n')
    emit_bytes(out, clock_atlas)
    out.write('};\nstatic const Glyph pad_digit_glyphs[10]={\n')
    emit_rows(out, pad_tables[0])
    out.write('};\nstatic const uint8_t pad_digit_alpha[]={\n')
    emit_bytes(out, pad_atlas)
    out.write('};\n#endif\n')
sources = [SANS, MONO, MONO_FALLBACK] + [Path(f'/usr/share/fonts/noto/NotoSans-{name}.ttf') for name in sorted(set(FALLBACK.values()))]
(ROOT / 'font-provenance.json').write_text(json.dumps({
    'interface': 'Adwaita Sans (Inter-based), SIL OFL 1.1', 'terminal': 'JetBrains Mono with Adwaita Mono fallback, SIL OFL 1.1',
    'fallback': 'Noto Sans, SIL OFL 1.1', 'styles': STYLES, 'gamma': GAMMA,
    'fallback_codepoints': [hex(point) for point in missing],
    'alpha_bytes': {'ascii': len(atlas), 'extra': len(extra_atlas), 'terminal': len(mono_atlas)},
    'runtime': 'pre-rasterized alpha glyphs; no font engine',
    'sources': [{'file': path.name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()} for path in sources],
}, indent=2) + '\n')
print(json.dumps({'ascii': len(atlas), 'extra': len(extra_atlas), 'terminal': len(mono_atlas), 'fallback': len(missing)}))
