#!/usr/bin/env python3
"""Write zones_data.h: the time zones the installer offers, from the tz database's zone1970.tab.

Each zone keeps its id (Europe/Kyiv), a city label, its region, its UTC offsets in January
and July (minutes), so the list can say "UTC+2 / +3" without tz data in the recovery, and the
POSIX TZ rule from the end of its TZif file (EET-2EEST,M3.5.0/3,M10.5.0/4), which keeps the
recovery clock right through summer time. The new system checks the id against its own
/usr/share/zoneinfo.

    tools/generate_zones.py [ZONE1970_TAB]   (default /usr/share/zoneinfo/zone1970.tab)
"""
from datetime import datetime
from pathlib import Path
import sys
from zoneinfo import ZoneInfo

REGIONS = ('Europe', 'America', 'Asia', 'Africa', 'Australia', 'Pacific', 'Atlantic', 'Indian', 'Antarctica', 'Arctic')


def offset(zone, month):
    return int(datetime(2026, month, 15, 12, tzinfo=ZoneInfo(zone)).utcoffset().total_seconds() // 60)


def posix(zone, root=Path('/usr/share/zoneinfo')):
    data = (root / zone).read_bytes()
    if data[:4] != b'TZif' or data[4:5] < b'2':
        raise SystemExit('%s: no TZif v2 footer' % zone)
    end = data.rstrip(b'\n')
    rule = end[end.rfind(b'\n') + 1:].decode('ascii')
    if not rule or '"' in rule or '\\' in rule:
        raise SystemExit('%s: unusable TZ rule %r' % (zone, rule))
    return rule


def label(zone):
    parts = zone.split('/')
    city = parts[-1].replace('_', ' ')
    return '%s (%s)' % (city, parts[1].replace('_', ' ')) if len(parts) == 3 else city


def main(argv):
    source = Path(argv[1] if len(argv) > 1 else '/usr/share/zoneinfo/zone1970.tab')
    zones = []
    for line in source.read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        zone = line.split('\t')[2]
        region = zone.split('/')[0]
        if region not in REGIONS:
            continue
        zones.append((REGIONS.index(region), label(zone).casefold(), zone))
    zones.sort()
    out = ['/* Generated by tools/generate_zones.py from %s; do not edit. */' % source.name,
           '#ifndef A22X_ZONES_DATA_H', '#define A22X_ZONES_DATA_H',
           'typedef struct { const char *id, *city; unsigned char region; short january, july; const char *posix; } TzZone;',
           'static const char *const tz_regions[] = {%s};' % ', '.join('"%s"' % r for r in REGIONS),
           '#define TZ_REGIONS %du' % len(REGIONS), 'static const TzZone tz_zones[] = {']
    for region, _, zone in zones:
        out.append('    {"%s", "%s", %d, %d, %d, "%s"},' % (zone, label(zone), region, offset(zone, 1), offset(zone, 7), posix(zone)))
    out += ['};', '#define TZ_ZONES %du' % len(zones), '#endif', '']
    Path(__file__).resolve().parents[1].joinpath('zones_data.h').write_text('\n'.join(out))
    print('%d zones' % len(zones))


if __name__ == '__main__':
    main(sys.argv)
