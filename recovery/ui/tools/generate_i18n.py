#!/usr/bin/env python3
"""Build i18n_data.h from the gettext catalogs in i18n/.

msgid is the English text exactly as the C source spells it, so escapes stay as
written. A translation with different printf conversions stops the build, because
it would misread its arguments at run time.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SPEC = re.compile(r'%[-0-9.]*[a-zA-Z%]')
ORDER = ('uk', 'de', 'es', 'fr', 'pl', 'pt')
NAMES = {'uk': 'Українська', 'de': 'Deutsch', 'es': 'Español', 'fr': 'Français', 'pl': 'Polski', 'pt': 'Português'}


def unquote(line):
    return line[line.index('"') + 1:line.rindex('"')].replace('\\"', '"')


def read_po(path):
    catalog, msgid = {}, None
    for line in path.read_text().splitlines():
        if line.startswith('msgid '):
            msgid = unquote(line)
        elif line.startswith('msgstr ') and msgid:
            value = unquote(line)
            if value:
                catalog[msgid] = value
    return catalog


def c_order(value):
    return value.encode().decode('unicode_escape').encode('latin-1', 'replace') if False else value.replace('\\n', '\n').encode()


def quoted(value):
    return '"' + value.replace('"', '\\"') + '"'


def main():
    messages = [line for line in (ROOT / 'i18n/messages.txt').read_text().split('\n') if line]
    languages = [code for code in ORDER if (ROOT / 'i18n' / (code + '.po')).is_file()]
    catalogs = {code: read_po(ROOT / 'i18n' / (code + '.po')) for code in languages}
    ordered = sorted(messages, key=c_order)
    failed = False
    for code, catalog in catalogs.items():
        for msgid, text in catalog.items():
            if msgid in messages and SPEC.findall(msgid) != SPEC.findall(text):
                print(f'{code}: conversions differ: {msgid!r} -> {text!r}', file=sys.stderr)
                failed = True
    # A translation may only use what the font draws (2026-11-11: German and Polish low quotes
    # were shown as the replacement mark, since font_extra.h has no U+201E).
    drawn = set(range(32, 127)) | {10}
    found = re.search(r'extra_codepoints\[[^\]]*\]\s*=\s*\{([^}]*)\}', (ROOT / 'font_extra.h').read_text())
    drawn.update(int(value, 16) for value in re.findall(r'0x[0-9a-fA-F]+', found.group(1)))
    for code, catalog in catalogs.items():
        for msgid, text in catalog.items():
            absent = sorted({char for char in text.replace('\\n', '\n') if ord(char) not in drawn})
            if msgid in messages and absent:
                print(f'{code}: the font has no glyph for {absent!r} in {text!r}', file=sys.stderr)
                failed = True
    for msgid in messages:
        absent = sorted({char for char in msgid.replace('\\n', '\n') if ord(char) not in drawn})
        if absent:
            print(f'en: the font has no glyph for {absent!r} in {msgid!r}', file=sys.stderr)
            failed = True
    if failed:
        return 1
    with (ROOT / 'i18n_data.h').open('w') as out:
        out.write('/* Generated by tools/generate_i18n.py from the catalogs in i18n. */\n')
        out.write('#ifndef A22X_I18N_DATA_H\n#define A22X_I18N_DATA_H\n')
        out.write(f'#define LANGUAGE_COUNT {len(languages) + 1}\n')
        out.write('static const char*const language_codes[LANGUAGE_COUNT]={"en",' + ','.join(quoted(c) for c in languages) + '};\n')
        out.write('static const char*const language_names[LANGUAGE_COUNT]={"English",' + ','.join(quoted(NAMES[c]) for c in languages) + '};\n')
        out.write(f'#define MESSAGE_COUNT {len(ordered)}\n')
        out.write('static const char*const message_ids[MESSAGE_COUNT]={\n')
        out.write(',\n'.join(quoted(value) for value in ordered) + '\n};\n')
        out.write('static const char*const message_text[LANGUAGE_COUNT-1][MESSAGE_COUNT]={\n')
        for code in languages:
            out.write('{\n' + ',\n'.join(quoted(catalogs[code][value]) if value in catalogs[code] else 'NULL' for value in ordered) + '\n},\n')
        out.write('};\n#endif\n')
    done = {code: sum(value in catalogs[code] for value in ordered) for code in languages}
    print(len(ordered), 'messages', done)
    return 0


if __name__ == '__main__':
    sys.exit(main())
