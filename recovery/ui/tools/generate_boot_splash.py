#!/usr/bin/env python3
"""Write the kernel's boot splash from the UI's own splash page, so the two match exactly.

The UI draws the page with no bar; everything that differs from the page colour becomes
the logo block of mtk_boot_splash_logo.h. Usage: generate_boot_splash.py HEADER
"""
from pathlib import Path
import subprocess
import sys
import tempfile

UI = Path(__file__).resolve().parents[1]


def main():
    with tempfile.TemporaryDirectory() as temporary:
        out = Path(temporary) / 'splash.ppm'
        subprocess.run([str(UI / 'a22x-recovery-ui'), '--theme', 'graphite', '--preview', 'splash', '--render-native', str(out)], check=True,
                       capture_output=True)
        data = out.read_bytes()
    parts = data.split(b'\n', 3)
    width, height = map(int, parts[1].split())
    assert parts[0] == b'P6' and parts[2] == b'255', parts[:3]
    pixels = parts[3]
    row = width * 3
    background = pixels[(height // 8) * row:(height // 8) * row + 3]
    rows = [y for y in range(height) if pixels[y * row:(y + 1) * row] != background * width]
    x0, x1 = width, 0
    for y in rows:
        line = pixels[y * row:(y + 1) * row]
        columns = [x for x in range(width) if line[x * 3:x * 3 + 3] != background]
        x0, x1 = min(x0, columns[0]), max(x1, columns[-1] + 1)
    y0, y1 = rows[0], rows[-1] + 1
    logo = bytearray()
    for y in range(y0, y1):
        logo += pixels[y * row + x0 * 3:y * row + x1 * 3]
    print(f'canvas {width}x{height}, logo {x1 - x0}x{y1 - y0} at {x0},{y0}, background {background.hex()}', file=sys.stderr)
    with open(sys.argv[1], 'w') as header:
        header.write('/* SPDX-License-Identifier: GPL-2.0-only */\n/* Generated by a22x tools/generate_boot_splash.py. */\n')
        header.write(f'#define SPLASH_LOGO_X {x0}\n#define SPLASH_LOGO_Y {y0}\n#define SPLASH_LOGO_W {x1 - x0}\n#define SPLASH_LOGO_H {y1 - y0}\n')
        header.write(f'#define SPLASH_BACKGROUND 0x{background.hex()}\n')
        header.write('static const u8 splash_logo[] = {\n')
        for n in range(0, len(logo), 24):
            header.write(','.join(str(v) for v in logo[n:n + 24]) + ',\n')
        header.write('};\n')


if __name__ == '__main__':
    main()
