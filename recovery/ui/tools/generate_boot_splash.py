#!/usr/bin/env python3
"""Write the kernel's boot splash from the UI's own splash page, so the two match exactly.

The UI draws the page with no bar, once per built-in theme (2026-11-10: the splash follows the
theme /init reads from the saved settings). Everything that differs from the page colour in any
theme becomes the logo block of mtk_boot_splash_logo.h, the same block for every theme; the bar
uses each theme's panel2 (track) and accent (fill) from theme.h, as render_splash does.
Usage: generate_boot_splash.py HEADER
"""
from pathlib import Path
import re
import subprocess
import sys
import tempfile

UI = Path(__file__).resolve().parents[1]
THEMES = ('graphite', 'daylight', 'aurora')


def render(theme):
    with tempfile.TemporaryDirectory() as temporary:
        out = Path(temporary) / 'splash.ppm'
        subprocess.run([str(UI / 'a22x-recovery-ui'), '--theme', theme, '--preview', 'splash', '--render-native', str(out)],
                       check=True, capture_output=True)
        data = out.read_bytes()
    parts = data.split(b'\n', 3)
    width, height = map(int, parts[1].split())
    assert parts[0] == b'P6' and parts[2] == b'255', parts[:3]
    return width, height, parts[3]


def colours(theme):
    text = (UI / 'theme.h').read_text()
    block = re.search(r'\{\.code="%s".*?\.bento=(?:true|false)\}' % theme, text, re.S)
    assert block, theme
    found = {name: int(value, 16) for name, value in re.findall(r'\.(panel2|accent)=0x([0-9a-fA-F]{6})u', block.group(0))}
    return found['panel2'], found['accent']


def main():
    pages, backgrounds = {}, {}
    width = height = None
    for theme in THEMES:
        w, h, pixels = render(theme)
        assert width in (None, w) and height in (None, h)
        width, height, pages[theme] = w, h, pixels
        row = width * 3
        backgrounds[theme] = pixels[(height // 8) * row:(height // 8) * row + 3]
    row = width * 3
    x0, x1, y0, y1 = width, 0, height, 0
    for theme in THEMES:
        pixels, background = pages[theme], backgrounds[theme]
        for y in range(height):
            line = pixels[y * row:(y + 1) * row]
            if line == background * width:
                continue
            columns = [x for x in range(width) if line[x * 3:x * 3 + 3] != background]
            x0, x1, y0, y1 = min(x0, columns[0]), max(x1, columns[-1] + 1), min(y0, y), max(y1, y + 1)
    print(f'canvas {width}x{height}, logo {x1 - x0}x{y1 - y0} at {x0},{y0}', file=sys.stderr)
    with open(sys.argv[1], 'w') as header:
        header.write('/* SPDX-License-Identifier: GPL-2.0-only */\n/* Generated by a22x tools/generate_boot_splash.py. */\n')
        header.write(f'#define SPLASH_LOGO_X {x0}\n#define SPLASH_LOGO_Y {y0}\n#define SPLASH_LOGO_W {x1 - x0}\n#define SPLASH_LOGO_H {y1 - y0}\n')
        header.write(f'#define SPLASH_THEMES {len(THEMES)}\n')
        header.write('static const char *const splash_theme_names[SPLASH_THEMES] = { %s };\n' % ', '.join(f'"{t}"' for t in THEMES))
        header.write('static const u32 splash_backgrounds[SPLASH_THEMES] = { %s };\n' % ', '.join('0x' + backgrounds[t].hex() for t in THEMES))
        header.write('static const u32 splash_tracks[SPLASH_THEMES] = { %s };\n' % ', '.join('0x%06x' % colours(t)[0] for t in THEMES))
        header.write('static const u32 splash_fills[SPLASH_THEMES] = { %s };\n' % ', '.join('0x%06x' % colours(t)[1] for t in THEMES))
        header.write('static const u8 splash_logos[SPLASH_THEMES][SPLASH_LOGO_W * SPLASH_LOGO_H * 3] = {\n')
        for theme in THEMES:
            pixels = pages[theme]
            logo = bytearray()
            for y in range(y0, y1):
                logo += pixels[y * row + x0 * 3:y * row + x1 * 3]
            header.write('{\n')
            for n in range(0, len(logo), 24):
                header.write(','.join(str(v) for v in logo[n:n + 24]) + ',\n')
            header.write('},\n')
        header.write('};\n')


if __name__ == '__main__':
    main()
