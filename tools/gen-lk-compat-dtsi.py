#!/usr/bin/env python3
"""Turn the stock a22x kernel DTB into an "LK compatibility" base for mainline.

The Samsung/MediaTek LK looks up many nodes (by path and by compatible) in the
kernel DTB, applies the stock dtbo.img overlay to it and panics if something it
expects is missing. So the mainline DTB keeps the whole stock tree, but every
top-level node that mainline does not need is forced to status = "disabled"
so the kernel never instantiates it.

usage: gen-lk-compat-dtsi.py stock.dtb out.dtsi
"""
import re
import subprocess
import sys

# Top-level nodes (by name, without unit address handling beyond exact match)
# that stay as they are in the stock tree.
KEEP = {
    "chosen", "cpus", "psci", "aliases", "memory", "reserved-memory",
    "interrupt-controller", "timer", "dummy26m", "clocks", "serial@11002000",
}

dts = subprocess.run(["dtc", "-q", "-I", "dtb", "-O", "dts", sys.argv[1]],
                     check=True, capture_output=True, text=True).stdout
lines = dts.splitlines()
assert lines[0] == "/dts-v1/;"

out = []
i = 0
node_re = re.compile(r"^\t(?:([\w-]+): )?([^\s]+) \{$")
while i < len(lines):
    line = lines[i]
    m = node_re.match(line)
    if not m:
        if line != "/dts-v1/;":
            out.append(line)
        i += 1
        continue

    # Collect the whole top-level node.
    j = i + 1
    while lines[j] != "\t};":
        j += 1
    body = lines[i:j + 1]
    name = m.group(2)
    i = j + 1

    if name == "__symbols__":
        continue  # regenerated from labels by dtc -@

    if name == "reserved-memory":
        # Child regions without no-map are dynamic (CMA, shared buffers):
        # keep them in the tree for LK, but do not let the kernel allocate them.
        res, k = [], 0
        while k < len(body):
            res.append(body[k])
            if re.match(r"^\t\t[^\t].*\{$", body[k]):
                end = k + 1
                while body[end] != "\t\t};":
                    end += 1
                child = body[k + 1:end]
                if not any(l.strip() == "no-map;" for l in child):
                    child = [l for l in child if not l.strip().startswith("status =")]
                    child.insert(0, '\t\t\tstatus = "disabled";')
                res.extend(child)
                res.append(body[end])
                k = end + 1
                continue
            k += 1
        body = res
    elif name == "serial@11002000":
        body = [l for l in body if not re.match(r"^\t\t(clocks|clock-names|dmas|dma-names) =", l)]
        body.insert(-1, "\t\tclocks = <&uart_clk>, <&uart_clk>;")
        body.insert(-1, '\t\tclock-names = "baud", "bus";')
        body.insert(-1, '\t\tstatus = "okay";')
    elif name not in KEEP:
        body = [l for l in body if not re.match(r"^\t\tstatus = ", l)]
        body.insert(1, '\t\tstatus = "disabled";')

    out.extend(body)

with open(sys.argv[2], "w") as f:
    f.write("// SPDX-License-Identifier: GPL-2.0-only\n")
    f.write("/* Generated by gen-lk-compat-dtsi.py from the stock A226BXXSBDZC3 boot.img DTB. Do not edit. */\n\n")
    f.write("\n".join(out) + "\n")
